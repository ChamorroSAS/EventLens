import { randomBytes, randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { withIsolatedTestDatabase } from './isolated-tests.mjs';
import { createPrismaClient, PrismaTransactions } from '../packages/database/dist/index.js';
import { AdminBootstrapService, DurableRecoveryAuthorityAdapter } from '../packages/identity/dist/index.js';
import { createApplication } from '../apps/api/dist/application.js';
import { readConfig } from '../apps/api/dist/platform/config/config.js';
import { createSpaStaticServer } from '../apps/web/spa-server.mjs';

const { chromium, expect } = createRequire(new URL('../e2e/package.json', import.meta.url))('@playwright/test');
let phase = 'build';
const build = spawnSync('pnpm', ['--filter', '@eventlens/web', 'build'], { stdio: 'pipe' });
if (build.status !== 0) { console.error('ADMIN_ORGANIZER_BROWSER_BUILD_FAILED'); process.exit(1); }
try {
  await withIsolatedTestDatabase(async env => {
    phase = 'migration';
    const migrate = spawnSync(process.execPath, ['scripts/database.mjs', 'migrate'], { env, stdio: 'pipe' });
    if (migrate.status !== 0) throw new Error('migration');
    Object.assign(process.env, env);
    const directory = await mkdtemp(join(tmpdir(), 'organizer-browser-'));
    const client = createPrismaClient(env.DATABASE_URL);
    const transactions = new PrismaTransactions(client, 10000);
    const authority = new DurableRecoveryAuthorityAdapter({ storageDir: directory });
    await authority.initialize();
    const proof = randomBytes(32).toString('hex');
    let secret;
    const principal = await new AdminBootstrapService(transactions, proof).bootstrap({ identifier: 'browser-admin', operatorToken: proof }, async value => { secret = value; });
    const prepared = await authority.prepare({ operationId: randomUUID(), subjectRef: principal.id, fact: { type: 'CREDENTIAL_ROTATED', data: { subjectKind: 'ADMIN' } } });
    await authority.ackCommit(prepared.preparedReceipt, 1n);
    const webOrigin = `http://localhost:${env.SPA_PORT}`;
    const config = { ...readConfig({ ...env, WEB_ORIGIN: webOrigin }), localAdminAuthorityDir: directory };
    const { app } = await createApplication(config);
    await app.listen(Number(env.API_PORT), '127.0.0.1');
    const apiOrigin = `http://127.0.0.1:${env.API_PORT}`;
    const spa = createSpaStaticServer({ distDir: '/workspace/apps/web/dist/web/browser' });
    await new Promise(resolve => spa.listen(Number(env.SPA_PORT), '127.0.0.1', resolve));
    const browser = await chromium.launch();
    const context = await browser.newContext();
    const organizerContext = await browser.newContext();
    const routeApi = async target => target.route('**/api/**', async route => {
      const url = new URL(route.request().url());
      const response = await route.fetch({ url: `${apiOrigin}${url.pathname}${url.search}`, headers: { ...route.request().headers(), origin: webOrigin } });
      await route.fulfill({ response });
    });
    await routeApi(context); await routeApi(organizerContext);
    try {
      phase = 'admin login';
      const page = await context.newPage();
      await page.goto(`${webOrigin}/admin/organizadores`);
      await page.waitForURL('**/admin/ingresar**');
      await page.locator('#admin-login-identifier').fill('browser-admin');
      await page.locator('#admin-login-secret').fill(secret);
      await page.locator('#admin-login-submit-btn').click();
      await page.waitForURL('**/admin/organizadores');
      secret = undefined;
      phase = 'create organizer';
      const email = `browser-${randomUUID()}@example.test`;
      await page.getByRole('button', { name: 'Crear organizador', exact: true }).click();
      await page.locator('#organizer-email').fill(email);
      await page.locator('#organizer-name').fill('Organizador de prueba');
      await page.locator('#organizer-reason').fill('Validación aislada de acceso Beta');
      await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
      await expect(page.locator('#temporary-password')).toBeVisible();
      const temporaryPassword = await page.locator('#temporary-password').inputValue();
      if (!temporaryPassword) throw new Error('password absent');
      await page.getByRole('button', { name: 'Ya guardé la credencial' }).click();
      await expect(page.getByRole('button', { name: `Gestionar cuenta de ${email}` })).toBeVisible();
      const account = (await transactions.run(tx => tx.query('SELECT id FROM organizer_account WHERE email_normalized=$1', email)))[0];
      phase = 'temporary login';
      const org = await organizerContext.newPage();
      await org.goto(`${webOrigin}/ingresar`);
      await org.locator('#organizer-login-email').fill(email);
      await org.locator('#organizer-login-password').fill(temporaryPassword);
      await org.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
      await org.waitForURL('**/cambiar-contrasena');
      await org.reload();
      await expect(org.locator('#password-change-title')).toBeVisible();
      await org.goto(`${webOrigin}/mis-eventos`);
      await org.waitForURL('**/cambiar-contrasena');
      const denial = await org.evaluate(async () => (await fetch('/api/v1/organizer/events')).status);
      if (denial !== 403) throw new Error('ordinary API not denied');
      phase = 'mandatory password change';
      const newPassword = 'DifferentPersonalPassword123!';
      await org.locator('#password-change-current').fill(temporaryPassword);
      await org.locator('#password-change-new').fill(newPassword);
      await org.locator('#password-change-confirm').fill(newPassword);
      await org.locator('#password-change-adult').check();
      await org.getByRole('button', { name: 'Guardar contraseña', exact: true }).click();
      await org.waitForURL('**/ingresar?passwordChanged=1');
      await expect(org.getByText('Contraseña actualizada. Ingresa con tu nueva contraseña.')).toBeVisible();
      await org.locator('#organizer-login-email').fill(email);
      await org.locator('#organizer-login-password').fill(newPassword);
      await org.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
      await org.goto(`${webOrigin}/mis-eventos`);
      await expect(org.getByRole('heading', { name: 'Mis eventos', exact: true })).toBeVisible();
      phase = 'preserved event';
      const eventId = randomUUID();
      await transactions.run(tx => tx.execute(`INSERT INTO event (id,organizer_id,name,status,timezone) VALUES ($1,$2,'Evento conservado','DRAFT','America/Bogota')`, eventId, account.id));
      phase = 'edit name';
      await page.getByRole('button', { name: `Gestionar cuenta de ${email}` }).click();
      await page.locator('#organizer-name').fill('Nombre actualizado');
      await page.locator('#organizer-reason').fill('Validar edición de nombre');
      await page.getByRole('button', { name: 'Guardar nombre', exact: true }).click();
      await expect(page.getByText('Nombre actualizado', { exact: true })).toBeVisible();
      phase = 'disable';
      await page.getByRole('button', { name: `Gestionar cuenta de ${email}` }).click();
      await page.locator('#organizer-reason').fill('Validar deshabilitación sin borrado');
      await page.getByRole('button', { name: 'Deshabilitar acceso', exact: true }).click();
      await page.getByRole('button', { name: 'Confirmar', exact: true }).click();
      await expect(page.getByText('Deshabilitado', { exact: true })).toBeVisible();
      const denied = await org.evaluate(async () => (await fetch('/api/v1/organizer/events')).status);
      if (denied !== 401) throw new Error('disabled session still active');
      if ((await transactions.run(tx => tx.query('SELECT id FROM event WHERE id=$1 AND organizer_id=$2',eventId,account.id))).length !== 1) throw new Error('event not preserved');
      phase = 'enable';
      await page.getByRole('button', { name: `Gestionar cuenta de ${email}` }).click();
      await page.locator('#organizer-reason').fill('Validar habilitación controlada');
      await page.getByRole('button', { name: 'Habilitar acceso', exact: true }).click();
      await page.getByRole('button', { name: 'Confirmar', exact: true }).click();
      await expect(page.getByText('Habilitado', { exact: true })).toBeVisible();
      if (await org.evaluate(async () => (await fetch('/api/v1/organizer/events')).status) !== 401) throw new Error('old session resurrected');
      phase = 'mobile layout';
      await page.setViewportSize({ width: 390, height: 844 });
      if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('horizontal overflow');
      console.log('ADMIN_ORGANIZER_BROWSER_PASS: create, mandatory change, API fence, edit, disable/enable, preserved events, revoked sessions and mobile layout.');
    } finally {
      await browser.close(); await app.close(); await client.$disconnect();
      await new Promise(resolve => spa.close(resolve));
      await rm(directory, { recursive: true, force: true });
    }
  });
} catch {
  console.error(`ADMIN_ORGANIZER_BROWSER_FAILED: ${phase}. No credentials, screenshot or trace emitted.`);
  process.exitCode = 1;
}
