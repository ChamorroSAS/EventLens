#!/usr/bin/env bash
# Phoeve Beta — one-time, idempotent host preparation (Etapa 1).
#
# Run by an authorised operator over SSM Session Manager, never by CI. It:
#
#   * installs the container runtime from the Amazon Linux 2023 repositories,
#   * formats (only once) and mounts each dedicated data volume with a marker,
#   * installs the stable deployment entry point at /usr/local/sbin/phoeve-deploy,
#   * installs the systemd unit that starts the stack on boot.
#
# It contains no secrets and does not start the stack.
#
# Usage:
#   sudo ./bootstrap-host.sh --database-volume vol-xxxx --media-volume vol-yyyy
#
set -euo pipefail

PHOEVE_ROOT=/srv/phoeve/beta
DEPLOY_SOURCE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

log() { printf '[bootstrap] %s\n' "$*"; }
die() { printf '[bootstrap] ERROR: %s\n' "$*" >&2; exit 1; }

[[ "$(id -u)" -eq 0 ]] || die "run as root (sudo)"

database_volume=""
media_volume=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --database-volume) database_volume="${2:?}"; shift 2 ;;
    --media-volume) media_volume="${2:?}"; shift 2 ;;
    --help|-h) sed -n '2,20p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done

[[ -n "$database_volume" ]] || die "--database-volume is required"
[[ "$database_volume" =~ ^vol-[0-9a-f]+$ ]] || die "invalid database volume id: $database_volume"
if [[ -n "$media_volume" && ! "$media_volume" =~ ^vol-[0-9a-f]+$ ]]; then
  die "invalid media volume id: $media_volume"
fi

# --- Container runtime -----------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  log "installing the container runtime from the Amazon Linux 2023 repositories"
  dnf install -y docker
fi
systemctl enable --now docker
log "container runtime: $(docker --version)"

# --- Data volumes ----------------------------------------------------------
# Volumes are resolved by id, never by a guessed device node, and each mount
# carries a marker file so the stack can prove which volume it is using.
resolve_volume_device() {
  local volume_id="$1" device
  for candidate in \
    "/dev/disk/by-id/nvme-Amazon_Elastic_Block_Storage_${volume_id}" \
    "/dev/disk/by-id/nvme-Amazon_Elastic_Block_Storage_${volume_id}-part1" \
    "/dev/disk/by-id/nvme-Amazon_Elastic_Block_Storage_${volume_id}-vol1"; do
    if [[ -e "$candidate" ]]; then
      readlink -f "$candidate"
      return 0
    fi
  done
  for device in /dev/nvme*n1; do
    [[ -e "$device" ]] || continue
    if [[ "$(cat "/sys/block/$(basename "$device")/serial" 2>/dev/null || true)" == *"${volume_id}"* ]]; then
      printf '%s\n' "$device"
      return 0
    fi
  done
  return 1
}

prepare_volume() {
  local volume_id="$1" mount_path="$2" label="$3"
  local device current_label current_uuid

  if ! device="$(resolve_volume_device "$volume_id")"; then
    die "volume ${volume_id} is not attached to this instance"
  fi

  current_label="$(lsblk -no LABEL "$device" 2>/dev/null | head -n1 || true)"
  if [[ -z "$current_label" ]]; then
    log "formatting ${device} as ext4 (${label})"
    mkfs.ext4 -q -L "$label" "$device"
  else
    log "keeping the existing filesystem on ${device} (label ${current_label})"
  fi

  install -d -m 0755 "$mount_path"
  current_uuid="$(blkid -s UUID -o value "$device")"
  [[ -n "$current_uuid" ]] || die "could not read the UUID of ${device}"

  # nofail keeps the host reachable through SSM if a volume goes missing; the
  # systemd unit and the mount guard still refuse to start the stack without it.
  if ! grep -q "UUID=${current_uuid}" /etc/fstab; then
    printf 'UUID=%s %s ext4 defaults,nofail 0 2\n' "$current_uuid" "$mount_path" >> /etc/fstab
  fi

  mountpoint -q "$mount_path" || mount "$mount_path"
  printf '%s\n' "$volume_id" > "${mount_path}/.phoeve-volume-id"
  log "mounted ${volume_id} at ${mount_path}"
}

prepare_volume "$database_volume" "${PHOEVE_ROOT}/postgres" phoeve-database
if [[ -n "$media_volume" ]]; then
  prepare_volume "$media_volume" "${PHOEVE_ROOT}/media" phoeve-media
fi

# Declared volumes are what the mount guard and the systemd unit verify. Media is
# only declared when it is actually part of this deployment.
install -d -m 0755 /etc/phoeve
{
  printf '# Generated by bootstrap-host.sh. Declared data volumes.\n'
  printf 'DATABASE_VOLUME=%s\n' "$database_volume"
  if [[ -n "$media_volume" ]]; then
    printf 'MEDIA_VOLUME=%s\n' "$media_volume"
  fi
} > /etc/phoeve/beta-volumes.env
chmod 0644 /etc/phoeve/beta-volumes.env

# --- Layout ----------------------------------------------------------------
install -d -m 0755 "$PHOEVE_ROOT"
install -d -m 0700 "$PHOEVE_ROOT/releases"
install -d -m 0755 "$PHOEVE_ROOT/caddy/data" "$PHOEVE_ROOT/caddy/config"

# Stable deployment entry point: CI never writes these files.
install -m 0755 "${DEPLOY_SOURCE_DIR}/phoeve-deploy" /usr/local/sbin/phoeve-deploy
install -m 0755 "${DEPLOY_SOURCE_DIR}/render-env.sh" /usr/local/sbin/phoeve-render-env
install -m 0755 "${DEPLOY_SOURCE_DIR}/mount-guard.sh" /usr/local/sbin/phoeve-mount-guard
install -m 0644 "${DEPLOY_SOURCE_DIR}/phoeve-beta.service" /etc/systemd/system/phoeve-beta.service

systemctl daemon-reload
systemctl enable phoeve-beta.service

log "host prepared."
log "next: sudo /usr/local/sbin/phoeve-render-env  (renders /srv/phoeve/beta/app.env from SSM)"
log "the stack was NOT started by this script."
