#!/usr/bin/env bash
# Phoeve Beta — render /srv/phoeve/beta/app.env from SSM Parameter Store.
#
# Secret values are read straight from SSM SecureString on the host and written
# to a 0600 file. They never pass through CI, Git, Terraform state or a command
# line that ends up in a log.
#
# Parameters expected (created by an authorised operator, not by Terraform):
#   <prefix>/postgres-password      SecureString
#   <prefix>/identity-pepper        SecureString
#
# Usage: sudo /usr/local/sbin/phoeve-render-env [--prefix /phoeve/beta]
set -euo pipefail

PHOEVE_ROOT=/srv/phoeve/beta
prefix=/phoeve/beta
while [[ $# -gt 0 ]]; do
  case "$1" in
    --prefix) prefix="${2:?}"; shift 2 ;;
    *) printf 'unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done

[[ "$(id -u)" -eq 0 ]] || { printf 'run as root (sudo)\n' >&2; exit 1; }
command -v aws >/dev/null 2>&1 || { printf 'aws cli v2 is required\n' >&2; exit 1; }

read_parameter() {
  local name="$1"
  aws ssm get-parameter \
    --name "${prefix}/${name}" \
    --with-decryption \
    --query 'Parameter.Value' \
    --output text
}

postgres_password="$(read_parameter postgres-password)"
identity_pepper="$(read_parameter identity-pepper)"

[[ ${#postgres_password} -ge 16 ]] || { printf 'postgres-password from SSM is too short\n' >&2; exit 1; }
[[ ${#identity_pepper} -ge 32 ]] || { printf 'identity-pepper from SSM is too short\n' >&2; exit 1; }

install -d -m 0755 "$PHOEVE_ROOT"
umask 077
tmp="$(mktemp "${PHOEVE_ROOT}/app.env.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

cat > "$tmp" <<EOF
# Generated by phoeve-render-env on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit.
# Non-secret values mirror infra/beta/beta.env.example.
PHOEVE_DATA_ROOT=${PHOEVE_ROOT}
PUBLIC_ENTRY_BASE_URL=https://beta.phoeve.com
PHOEVE_SITE_ADDRESS=beta.phoeve.com
ACME_EMAIL=${ACME_EMAIL:-ops@phoeve.com}
HTTP_BIND=0.0.0.0
HTTP_PORT=80
HTTPS_PORT=443
POSTGRES_USER=phoeve
POSTGRES_DB=phoeve
POSTGRES_MEM_LIMIT=1g
API_MEM_LIMIT=1g
POSTGRES_PASSWORD=${postgres_password}
IDENTITY_PEPPER_SECRET=${identity_pepper}
EOF

chmod 0600 "$tmp"
mv "$tmp" "${PHOEVE_ROOT}/app.env"
trap - EXIT
printf 'rendered %s/app.env (mode 0600)\n' "$PHOEVE_ROOT"
